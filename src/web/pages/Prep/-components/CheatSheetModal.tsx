import { useMemo, useState } from 'react';
import type { Prep as PrepData, ProfileFact } from '../../../api';
import { Badge } from '../../../components/ui/badge';
import { Button } from '../../../components/ui/button';
import { formatDateTime } from '../../../format';

export function CheatSheetModal({
  data,
  facts,
  onClose,
}: {
  data: PrepData;
  facts: ProfileFact[];
  onClose: () => void;
}) {
  const [copied, setCopied] = useState(false);
  const next = data.interviews.find((i) => i.outcome === 'pending');
  const postingTopics = data.topics.filter((t) => t.source === 'posting');
  const gaps = data.topics.filter((t) => t.gap);

  const plainTextBrief = useMemo(() => {
    const lines = [
      `INTERVIEW CHEAT SHEET: ${data.application.title} at ${data.application.employer}`,
      `Generated by Career Strike on ${new Date().toLocaleDateString()}`,
      `------------------------------------------------------------`,
      next ? `Scheduled: ${next.stage} on ${formatDateTime(next.scheduledAt)} (${next.format})` : `Status: Preparing`,
      '',
      `KEY REQUIREMENTS & POSTING TOPICS:`,
      ...postingTopics.map((t) => `• ${t.title}${t.quote ? ` (Posting: "${t.quote}")` : ''}`),
      '',
      `IDENTIFIED GAPS & DEFENSE STRATEGY:`,
      gaps.length > 0
        ? gaps
            .map((g) => `• ${g.title}: Acknowledge honestly; anchor on adjacent concepts and fast ramp-up ability.`)
            .join('\n')
        : '• No direct gaps detected against your verified profile facts.',
      '',
      `YOUR ANCHORED STRENGTHS:`,
      ...facts
        .filter((f) => f.approved)
        .slice(0, 8)
        .map((f) => {
          const name = typeof f.value.name === 'string' ? f.value.name : '';
          const role =
            typeof f.value.title === 'string' && typeof f.value.company === 'string'
              ? `${f.value.title} at ${f.value.company}`
              : '';
          return `• [${f.kind.toUpperCase()}] ${name || role || JSON.stringify(f.value)}`;
        }),
      '',
      `STAR METHOD CHECKLIST:`,
      `• Situation: State context, scale, and constraints succinctly.`,
      `• Task: Define the explicit objective and your personal responsibility.`,
      `• Action: Detail the engineering architecture, tools, tradeoffs, and code.`,
      `• Result: Highlight concrete metrics (latency, reliability, cost, adoption).`,
    ];
    return lines.join('\n');
  }, [data, facts, next, postingTopics, gaps]);

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(plainTextBrief);
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    } catch {
      // ignore
    }
  };

  return (
    <div
      className="fixed inset-0 z-50 bg-black/60 backdrop-blur-xs flex items-center justify-center p-4 overflow-y-auto"
      onClick={onClose}
      role="presentation"
    >
      <div
        className="relative w-full max-w-4xl max-h-[90vh] overflow-y-auto bg-card text-card-foreground rounded-xl border border-border shadow-2xl p-6 sm:p-8 space-y-6"
        role="dialog"
        aria-modal="true"
        aria-labelledby="cs-title"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="flex flex-col sm:flex-row items-start justify-between gap-4 pb-4 border-b border-border">
          <div>
            <p className="text-xs uppercase tracking-wider font-semibold text-muted-foreground">
              1-Page Interview Brief
            </p>
            <h2 id="cs-title" className="text-xl sm:text-2xl font-bold tracking-tight text-foreground">
              {data.application.title} · {data.application.employer}
            </h2>
            {next && (
              <p className="text-sm text-muted-foreground mt-1">
                Upcoming: <strong className="text-foreground">{next.stage}</strong> · {formatDateTime(next.scheduledAt)}{' '}
                ({next.format.replace('_', '-')})
              </p>
            )}
          </div>
          <div className="flex gap-2 shrink-0">
            <Button type="button" size="sm" variant="secondary" onClick={handleCopy}>
              {copied ? '✓ Copied' : '📋 Copy Brief'}
            </Button>
            <Button type="button" size="sm" variant="ghost" onClick={() => window.print()}>
              🖨️ Print
            </Button>
            <Button type="button" size="sm" variant="ghost" onClick={onClose} aria-label="Close brief">
              ✕
            </Button>
          </div>
        </div>

        <div className="space-y-6">
          <div className="rounded-lg border border-border/70 bg-card/60 p-4 space-y-3">
            <h3 className="text-base font-semibold text-foreground">Posting Requirements &amp; Focus</h3>
            <ul className="divide-y divide-border/60 text-sm">
              {postingTopics.map((t) => (
                <li key={t.id} className="py-2.5 first:pt-0 last:pb-0">
                  <strong className="text-foreground">{t.title}</strong>
                  {t.quote && <span className="text-muted-foreground"> — “{t.quote}”</span>}
                </li>
              ))}
            </ul>
          </div>

          <div className="rounded-lg border border-border/70 bg-card/60 p-4 space-y-3">
            <h3 className="text-base font-semibold text-foreground">Gap Defense Strategy</h3>
            {gaps.length > 0 ? (
              <ul className="divide-y divide-border/60 text-sm">
                {gaps.map((g) => (
                  <li key={g.id} className="py-2.5 first:pt-0 last:pb-0">
                    <div className="flex items-center gap-2">
                      <Badge variant="destructive">Gap</Badge>
                      <strong className="text-foreground">{g.title}</strong>
                    </div>
                    <p className="text-xs text-muted-foreground mt-1">
                      Acknowledge frankly if asked; point to adjacent competencies and past fast-learning evidence.
                    </p>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="text-sm text-muted-foreground">✓ No critical skill gaps identified against this posting.</p>
            )}
          </div>

          <div className="rounded-lg border border-border/70 bg-card/60 p-4 space-y-3">
            <h3 className="text-base font-semibold text-foreground">Your Anchored Verified Strengths</h3>
            <div className="flex flex-wrap gap-1.5 pt-1">
              {facts
                .filter((f) => f.approved)
                .slice(0, 10)
                .map((f) => {
                  const label =
                    typeof f.value.name === 'string'
                      ? f.value.name
                      : typeof f.value.title === 'string'
                        ? f.value.title
                        : '';
                  return label ? (
                    <span
                      key={f.id}
                      className="inline-flex items-center rounded-md border border-border bg-secondary/60 px-2.5 py-1 text-xs font-medium text-secondary-foreground"
                    >
                      {label}
                    </span>
                  ) : null;
                })}
            </div>
          </div>

          <div className="rounded-lg border border-border/70 bg-card/60 p-4 space-y-3">
            <h3 className="text-base font-semibold text-foreground">⭐ STAR Response Quick Guide</h3>
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 text-sm">
              <div className="rounded-md border border-border/50 bg-background/50 p-3">
                <strong className="text-foreground">S · Situation</strong>
                <p className="text-xs text-muted-foreground mt-1">
                  1-2 sentences setting scope, architecture, scale, and business urgency.
                </p>
              </div>
              <div className="rounded-md border border-border/50 bg-background/50 p-3">
                <strong className="text-foreground">T · Task</strong>
                <p className="text-xs text-muted-foreground mt-1">
                  The specific deliverable you individually owned and were accountable for.
                </p>
              </div>
              <div className="rounded-md border border-border/50 bg-background/50 p-3">
                <strong className="text-foreground">A · Action</strong>
                <p className="text-xs text-muted-foreground mt-1">
                  Technical decisions, tradeoffs considered, how you unblocked collaborators.
                </p>
              </div>
              <div className="rounded-md border border-border/50 bg-background/50 p-3">
                <strong className="text-foreground">R · Result</strong>
                <p className="text-xs text-muted-foreground mt-1">
                  Quantitative outcome: latency reduced, uptime increased, revenue unlocked.
                </p>
              </div>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}
