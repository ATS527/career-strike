import { useMemo, useState } from 'react';
import type { Prep as PrepData, ProfileFact } from '../../../api';
import { Button } from '../../../components/ui/button';
import { formatDateTime } from '../../../format';

export function CheatSheetModal({
  data,
  facts,
  onClose,
}: {
  data: PrepData;
  facts: ProfileFact[];
  onClose: () => void;
}) {
  const [copied, setCopied] = useState(false);
  const next = data.interviews.find((i) => i.outcome === 'pending');
  const postingTopics = data.topics.filter((t) => t.source === 'posting');
  const gaps = data.topics.filter((t) => t.gap);

  const plainTextBrief = useMemo(() => {
    const lines = [
      `INTERVIEW CHEAT SHEET: ${data.application.title} at ${data.application.employer}`,
      `Generated by Career Strike on ${new Date().toLocaleDateString()}`,
      `------------------------------------------------------------`,
      next ? `Scheduled: ${next.stage} on ${formatDateTime(next.scheduledAt)} (${next.format})` : `Status: Preparing`,
      '',
      `KEY REQUIREMENTS & POSTING TOPICS:`,
      ...postingTopics.map((t) => `• ${t.title}${t.quote ? ` (Posting: "${t.quote}")` : ''}`),
      '',
      `IDENTIFIED GAPS & DEFENSE STRATEGY:`,
      gaps.length > 0
        ? gaps
            .map((g) => `• ${g.title}: Acknowledge honestly; anchor on adjacent concepts and fast ramp-up ability.`)
            .join('\n')
        : '• No direct gaps detected against your verified profile facts.',
      '',
      `YOUR ANCHORED STRENGTHS:`,
      ...facts
        .filter((f) => f.approved)
        .slice(0, 8)
        .map((f) => {
          const name = typeof f.value.name === 'string' ? f.value.name : '';
          const role =
            typeof f.value.title === 'string' && typeof f.value.company === 'string'
              ? `${f.value.title} at ${f.value.company}`
              : '';
          return `• [${f.kind.toUpperCase()}] ${name || role || JSON.stringify(f.value)}`;
        }),
      '',
      `STAR METHOD CHECKLIST:`,
      `• Situation: State context, scale, and constraints succinctly.`,
      `• Task: Define the explicit objective and your personal responsibility.`,
      `• Action: Detail the engineering architecture, tools, tradeoffs, and code.`,
      `• Result: Highlight concrete metrics (latency, reliability, cost, adoption).`,
    ];
    return lines.join('\n');
  }, [data, facts, next, postingTopics, gaps]);

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(plainTextBrief);
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    } catch {
      // ignore
    }
  };

  return (
    <div className="modal-backdrop" onClick={onClose} role="presentation">
      <div
        className="modal-card cheat-sheet-dialog"
        role="dialog"
        aria-modal="true"
        aria-labelledby="cs-title"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="cheat-sheet-header">
          <div>
            <p className="eyebrow">1-Page Interview Brief</p>
            <h2 id="cs-title">
              {data.application.title} · {data.application.employer}
            </h2>
            {next && (
              <p className="cheat-sheet-sub">
                Upcoming: <strong>{next.stage}</strong> · {formatDateTime(next.scheduledAt)} (
                {next.format.replace('_', '-')})
              </p>
            )}
          </div>
          <div className="cheat-sheet-actions flex gap-2">
            <Button type="button" size="sm" variant="secondary" onClick={handleCopy}>
              {copied ? '✓ Copied' : '📋 Copy Brief'}
            </Button>
            <Button type="button" size="sm" variant="ghost" onClick={() => window.print()}>
              🖨️ Print
            </Button>
            <Button type="button" size="sm" variant="ghost" onClick={onClose} aria-label="Close brief">
              ✕
            </Button>
          </div>
        </div>

        <div className="cheat-sheet-body">
          <div className="cheat-sheet-section">
            <h3>Posting Requirements &amp; Focus</h3>
            <ul className="disclosures">
              {postingTopics.map((t) => (
                <li key={t.id}>
                  <strong>{t.title}</strong>
                  {t.quote && <span className="muted"> — “{t.quote}”</span>}
                </li>
              ))}
            </ul>
          </div>

          <div className="cheat-sheet-section">
            <h3>Gap Defense Strategy</h3>
            {gaps.length > 0 ? (
              <ul className="disclosures">
                {gaps.map((g) => (
                  <li key={g.id}>
                    <span className="badge">Gap</span> <strong>{g.title}</strong>
                    <p className="help" style={{ margin: '0.2rem 0 0' }}>
                      Acknowledge frankly if asked; point to adjacent competencies and past fast-learning evidence.
                    </p>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="muted" style={{ fontSize: '0.88rem' }}>
                ✓ No critical skill gaps identified against this posting.
              </p>
            )}
          </div>

          <div className="cheat-sheet-section">
            <h3>Your Anchored Verified Strengths</h3>
            <div className="topic-evidence" style={{ marginTop: '0.4rem' }}>
              {facts
                .filter((f) => f.approved)
                .slice(0, 10)
                .map((f) => {
                  const label =
                    typeof f.value.name === 'string'
                      ? f.value.name
                      : typeof f.value.title === 'string'
                        ? f.value.title
                        : '';
                  return label ? (
                    <span key={f.id} className="evidence-chip evidence-chip--skill">
                      {label}
                    </span>
                  ) : null;
                })}
            </div>
          </div>

          <div className="cheat-sheet-section cheat-sheet-star">
            <h3>STAR Method Quick Reference</h3>
            <div className="star-grid">
              <div>
                <strong>S · Situation</strong>
                <p>1-2 sentences setting scope, architecture, scale, and business urgency.</p>
              </div>
              <div>
                <strong>T · Task</strong>
                <p>The specific deliverable you individually owned and were accountable for.</p>
              </div>
              <div>
                <strong>A · Action</strong>
                <p>Technical decisions, tradeoffs considered, how you unblocked collaborators.</p>
              </div>
              <div>
                <strong>R · Result</strong>
                <p>Quantitative outcome: latency reduced, uptime increased, revenue unlocked.</p>
              </div>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}
